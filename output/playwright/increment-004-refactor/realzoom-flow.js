async page => {
 const errors=[];page.on('pageerror',e=>errors.push(e.message));
 await page.goto('http://127.0.0.1:4184');
 const metrics=await page.evaluate(()=>({width:innerWidth,height:innerHeight,dpr:devicePixelRatio,scale:visualViewport.scale,scrollWidth:document.documentElement.scrollWidth}));
 if(metrics.width!==720||metrics.height!==450||metrics.dpr!==2||metrics.scale!==1)throw Error('Not actual 200% zoom '+JSON.stringify(metrics));
 await page.getByRole('button',{name:'Create project',exact:true}).click();
 await page.getByRole('button',{name:'New token',exact:true}).first().click();
 await page.getByLabel('Name',{exact:true}).fill('zoom exact');
 await page.getByRole('button',{name:'Create',exact:true}).click();
 await page.getByLabel('Red',{exact:true}).fill('0.123456789123456789123456789');
 await page.getByRole('button',{name:'Apply changes',exact:true}).click();
 if(await page.getByLabel('Red',{exact:true}).inputValue()!=='0.123456789123456789123456789')throw Error('Zoom raw text lost');
 await page.getByLabel('Red',{exact:true}).fill('1.0');
 await page.getByRole('button',{name:'Apply changes',exact:true}).click();
 await page.getByRole('alert').waitFor();
 await page.screenshot({path:'output/playwright/increment-004-refactor/final-realzoom-error.png'});
 await page.getByLabel('Red',{exact:true}).fill('0.4');
 await page.getByRole('button',{name:'Apply changes',exact:true}).click();
 await page.getByRole('button',{name:'Collapse token inspector'}).click();
 if(await page.getByLabel('Red',{exact:true}).isVisible())throw Error('Hidden authoring visible');
 await page.getByRole('button',{name:'Expand token inspector'}).click();
 await page.getByLabel('Red',{exact:true}).focus();
 await page.screenshot({path:'output/playwright/increment-004-refactor/final-realzoom-authoring.png'});
 await page.getByRole('button',{name:'Open project navigation'}).click();
 await page.getByRole('dialog',{name:'Project navigation'}).waitFor();
 await page.waitForFunction(()=>!!document.activeElement.closest('[role=dialog]'));
 await page.keyboard.press('Tab');
 if(!await page.evaluate(()=>!!document.activeElement.closest('[role=dialog]')))throw Error('Drawer lost focus');
 await page.keyboard.press('Escape');
 await page.waitForFunction(()=>document.activeElement?.getAttribute('aria-label')==='Open project navigation');
 if(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth))throw Error('Zoom horizontal overflow');
 if(errors.length)throw Error(JSON.stringify(errors));
 return {pass:true,metrics,errors};
}
