async page => {
  const errors=[]; page.on('pageerror', e=>errors.push(e.message));
  const description=' First zoom line\nSecond zoom line\nThird exact line  ';
  const exact='0.1234567890123456789012345678901234567890123456789';
  await page.getByRole('button',{name:'New token',exact:true}).first().click();
  await page.getByLabel('Name',{exact:true}).fill('zoom exact');
  await page.getByLabel('Description (optional)',{exact:true}).fill(description);
  await page.getByRole('button',{name:'Create',exact:true}).click();
  await page.getByLabel('Red',{exact:true}).fill(exact);
  await page.getByRole('button',{name:'Apply changes',exact:true}).click();
  if(await page.getByLabel('Red',{exact:true}).inputValue()!==exact)throw Error('Exact coordinate lost');
  await page.getByLabel('Red',{exact:true}).fill('1.0');
  await page.getByRole('button',{name:'Apply changes',exact:true}).click();
  await page.getByRole('alert').waitFor();
  const errorFocus=await page.evaluate(()=>({role:document.activeElement?.getAttribute('role'),text:document.activeElement?.textContent}));
  if(errorFocus.role!=='alert')throw Error('Error focus lost');
  await page.screenshot({path:'output/increment-005-zoom/authoring-error-200.png'});
  await page.getByLabel('Red',{exact:true}).fill(exact);
  await page.getByRole('button',{name:'Apply changes',exact:true}).click();
  await page.getByText('All authored data',{exact:true}).click();
  const raw=await page.locator('details').filter({has:page.getByText('All authored data',{exact:true})}).locator('pre').textContent();
  const token=JSON.parse(raw);
  if(token.description!==description||token.definition.assignments[0].value.components[0]!==exact)throw Error('Raw JSON metadata/value mismatch');
  await page.getByRole('button',{name:'Collapse token inspector'}).click();
  await page.getByLabel('Search color tokens',{exact:true}).fill('zoom exact');
  const row=page.locator('.token-row');
  const text=await row.textContent();
  if(!text.includes('R: '+exact)||!text.includes('Alpha: 1'))throw Error('Compact exact coordinates/Alpha missing');
  const metrics=await page.evaluate(()=>({width:innerWidth,height:innerHeight,dpr:devicePixelRatio,scale:visualViewport.scale,scrollWidth:document.documentElement.scrollWidth}));
  if(metrics.scrollWidth>metrics.width)throw Error('Horizontal overflow');
  await page.screenshot({path:'output/increment-005-zoom/example-200.png'});
  await page.getByRole('button',{name:'New token',exact:true}).first().click();
  if(await page.getByLabel('Description (optional)',{exact:true}).inputValue()!=='')throw Error('New description did not reset');
  await page.getByLabel('Description (optional)',{exact:true}).fill('Canceled description');
  const cancel=page.getByRole('button',{name:'Cancel',exact:true});
  await cancel.scrollIntoViewIfNeeded();
  const cancelBox=await cancel.boundingBox();
  if(!cancelBox||cancelBox.y<0||cancelBox.y+cancelBox.height>450)throw Error('Cancel not reachable');
  await page.screenshot({path:'output/increment-005-zoom/creation-actions-200.png'});
  await cancel.click();
  const returnFocus=await page.evaluate(()=>({tag:document.activeElement?.tagName,id:document.activeElement?.id,label:document.activeElement?.getAttribute('aria-label')}));
  await page.getByRole('button',{name:'New token',exact:true}).first().click();
  if(await page.getByLabel('Description (optional)',{exact:true}).inputValue()!=='')throw Error('Cancel description did not reset');
  await page.getByRole('button',{name:'Cancel',exact:true}).click();
  if(errors.length)throw Error(JSON.stringify(errors));
  return {pass:true,metrics,errorFocus,returnFocus,cancelBox,rawDescription:token.description,exact,errors,snapshot:await page.locator('body').ariaSnapshot()};
}
