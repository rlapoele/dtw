import {spawn} from 'node:child_process';
import {once} from 'node:events';
import {writeFileSync} from 'node:fs';
import assert from 'node:assert/strict';
import {OwnedProcessWatchdog} from './r5-owned-process-watchdog.mjs';
const path=new URL('./r5-watchdog-selftest-receipt.json',import.meta.url);
const evidence={date:new Date().toISOString(),scope:'Idle owned Node child only; no Chrome/performance run',watchdog:[],checkpoints:[],status:'running'};
const checkpoint=()=>{evidence.checkpoints.push({events:evidence.watchdog.length,status:evidence.status});writeFileSync(path,JSON.stringify(evidence,null,2));};
const child=spawn(process.execPath,['-e','setInterval(()=>{},1000)'],{stdio:'ignore'});
const closed=once(child,'exit');
const short=new OwnedProcessWatchdog(child,evidence,checkpoint,25);
await assert.rejects(()=>short.run('expiry-mechanism-selftest',()=>new Promise(()=>{})),/25ms owned process stop/);
const [code,signal]=await closed;
assert.equal(signal,'SIGKILL');assert(short.expired);
assert.equal(evidence.watchdog[0].pid,child.pid);
assert.equal(evidence.watchdog[1].event,'expired-checkpoint-before-kill');
assert.equal(evidence.watchdog[2].event,'owned-process-kill-issued');
assert(evidence.checkpoints.some(p=>p.events===2&&p.status==='watchdog-stopped'));
await assert.rejects(()=>short.run('must-not-retry',async()=>{}),/already stopped/);
const normalChild=spawn(process.execPath,['-e','setInterval(()=>{},1000)'],{stdio:'ignore'});
const normalClosed=once(normalChild,'exit');const normal=new OwnedProcessWatchdog(normalChild,evidence,checkpoint);
assert.equal(normal.milliseconds,30000);
assert.equal(await normal.run('normal-disarm-selftest',async()=>42),42);
assert.equal(normal.timer,undefined);normalChild.kill('SIGTERM');await normalClosed;
evidence.result={expirySignal:signal,shortTestBudget:25,productionDefault:normal.milliseconds,refusedFurtherOperations:true,normalDisarm:true};evidence.status='passed';checkpoint();console.log(JSON.stringify(evidence.result));
