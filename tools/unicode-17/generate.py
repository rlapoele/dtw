"""Generate pinned Unicode 17 tables. Python stdlib only; no host Unicode APIs.
Usage: python3 tools/unicode-17/generate.py /directory/with/ucd/files
Download the five named sources from https://www.unicode.org/Public/17.0.0/ucd/.
"""
import hashlib, json, pathlib, sys
source = pathlib.Path(sys.argv[1])
names = ['UnicodeData.txt', 'SpecialCasing.txt', 'CaseFolding.txt', 'DerivedCoreProperties.txt', 'DerivedNormalizationProps.txt']
manifest_path = pathlib.Path('tools/unicode-17/sources.json')
if manifest_path.exists():
    expected = json.loads(manifest_path.read_text())['sha256']
    for name in names:
        if hashlib.sha256((source/name).read_bytes()).hexdigest() != expected[name]:
            raise ValueError('Pinned Unicode source checksum mismatch: '+name)

def read(name):
    return (source / name).read_text()
def records(name):
    for line in read(name).splitlines():
        line = line.split('#')[0].strip()
        if line: yield [v.strip() for v in line.split(';')]
def points(text):
    bounds = [int(x,16) for x in text.split('..')]
    return range(bounds[0],bounds[-1]+1)
def sequence(text): return [int(x,16) for x in text.split()]
ccc, decomp, lower, fold = {}, {}, {}, {}
for row in records('UnicodeData.txt'):
    cp = int(row[0],16)
    if row[3] != '0': ccc[cp] = int(row[3])
    if row[5] and not row[5].startswith('<'): decomp[cp] = sequence(row[5])
    if row[13]: lower[cp] = sequence(row[13])
for row in records('SpecialCasing.txt'):
    if not row[4]: lower[int(row[0],16)] = sequence(row[1])
    elif row[4] == 'Final_Sigma': pass # the sole default contextual rule; implemented explicitly
    elif not row[4].split()[0] in ['tr','az','lt']: raise ValueError(row)
for row in records('CaseFolding.txt'):
    if row[1] in ['C','F']: fold[int(row[0],16)] = sequence(row[2])
properties = {p: [] for p in ['Cased','Case_Ignorable']}
for row in records('DerivedCoreProperties.txt'):
    if row[1] in properties:
        r = points(row[0]); properties[row[1]].append([r.start,r.stop-1])
excluded = set()
for row in records('DerivedNormalizationProps.txt'):
    if row[1] == 'Full_Composition_Exclusion': excluded.update(points(row[0]))
compose = {str(v[0])+','+str(v[1]): cp for cp,v in decomp.items() if len(v)==2 and cp not in excluded}
values = dict(combiningClass=ccc, decomposition=decomp, lowercase=lower, caseFold=fold, composition=compose, cased=properties['Cased'], caseIgnorable=properties['Case_Ignorable'])
out = pathlib.Path('src/domain/unicode-17-data.ts')
with out.open('w') as f:
    f.write('// Generated by tools/unicode-17/generate.py; Unicode 17.0.0; Unicode-3.0 license.\n')
    for name,value in values.items():
        typ = 'Readonly<Record<string, number>>' if name in ['combiningClass','composition'] else 'Readonly<Record<string, readonly number[]>>' if isinstance(value,dict) else 'readonly (readonly number[])[]'
        f.write('export const '+name+': '+typ+' = '+json.dumps(value,separators=(',',':'))+';\n')
manifest = {name: hashlib.sha256((source/name).read_bytes()).hexdigest() for name in names}
pathlib.Path('tools/unicode-17/sources.json').write_text(json.dumps({'version':'17.0.0','baseUrl':'https://www.unicode.org/Public/17.0.0/ucd/','sha256':manifest},indent=2)+'\n')
